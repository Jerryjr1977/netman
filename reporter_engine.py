def generate_report_json(scope: str, skimmer_hits: Optional[List[str]] = None,
                        ai_insights: str = "", version: str = "1.0") -> str:
    """Generate a JSON security report.

    Args:
        scope: Target scope/domain
        skimmer_hits: List of skimmer findings
        ai_insights: AI analysis summary
        version: Report version

    Returns:
        JSON formatted report
    """
    if not _validate_inputs(scope, skimmer_hits or [], ai_insights):
        return "{}"

    skimmer_hits = skimmer_hits or []
    stats = _calculate_stats(skimmer_hits, ai_insights)

    report_data = {
        "metadata": {
            "generated": datetime.now().isoformat(),
            "scope": scope,
            "version": version,
            "generator": "NetMan"
        },
        "findings": {
            "skimmer_hits": skimmer_hits,
            "ai_insights": ai_insights
        },
        "statistics": stats
    }

    try:
        json_report = json.dumps(report_data, indent=2)
        logger.info(f"Generated JSON report for scope: {scope}")
        return json_report
    except Exception as e:
        logger.error(f"Failed to generate JSON report: {e}")
        return "{}"

def save_report(file_path: str, report_text: str) -> tuple[bool, str]:
    """Save report to file atomically.

    Args:
        file_path: Target file path
        report_text: Report content

    Returns:
        Tuple of (success, message)
    """
    if not file_path:
        logger.error("No file path provided")
        return False, "No file path specified"

    if not isinstance(report_text, str):
        logger.error("Report text must be a string")
        return False, "Invalid report content type"

    if not report_text.strip():
        logger.error("Report text is empty")
        return False, "Report content is empty"

    try:
        # Create parent directory if needed
        parent_dir = os.path.dirname(file_path)
        if parent_dir and not os.path.exists(parent_dir):
            os.makedirs(parent_dir, exist_ok=True)
            logger.debug(f"Created directory: {parent_dir}")

        # Atomic write: write to temp file, then rename
        fd, temp_path = tempfile.mkstemp(suffix='.tmp', dir=parent_dir or '.')
        try:
            with os.fdopen(fd, 'w', encoding='utf-8') as f:
                f.write(report_text)
            shutil.move(temp_path, file_path)
            logger.info(f"Report saved: {file_path}")
            return True, "Report saved successfully"
        except Exception as e:
            if os.path.exists(temp_path):
                os.remove(temp_path)
            raise

    except IOError as e:
        logger.error(f"File I/O error: {e}")
        return False, f"I/O error: {e}"
    except Exception as e:
        logger.error(f"Save failed: {e}")
        return False, f"Save error: {e}"