import logging
import tempfile
import shutil
from datetime import datetime
from typing import Dict, List, Optional, Union

logging.basicConfig(level=logging.INFO, format='[%(levelname)s] %(message)s')
logger = logging.getLogger(__name__)

# Report format templates
MARKDOWN_TEMPLATE = """# NetMan Security Report

**Generated:** {timestamp}
**Target Scope:** {scope}
**Report Version:** {version}

## Executive Summary

This report contains findings from NetMan security analysis including passive skimmer detections and AI-powered vulnerability insights.

## Skimmer Findings

{skimmer_section}

## AI Analysis Summary

{ai_section}

## Technical Details

- **Analysis Duration:** {duration}
- **Total Findings:** {total_findings}
- **High Risk Items:** {high_risk}

---
*Report generated by NetMan v{version}*
"""

