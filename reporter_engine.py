def _validate_inputs(scope: str, skimmer_hits: List[str], ai_insights: str) -> bool:
    """Validate report input parameters."""
    if not isinstance(scope, str):
        logger.error("Scope must be a string")
        return False
    if not isinstance(skimmer_hits, list):
        logger.error("Skimmer hits must be a list")
        return False
    if not isinstance(ai_insights, str):
        logger.error("AI insights must be a string")
        return False
    return True

def _format_skimmer_section(skimmer_hits: List[str]) -> str:
    """Format skimmer findings for markdown."""
    if not skimmer_hits:
        return "No passive leaks detected."
    return "\n".join(f"* {hit}" for hit in skimmer_hits)

def _format_skimmer_html(skimmer_hits: List[str]) -> str:
    """Format skimmer findings for HTML."""
    if not skimmer_hits:
        return '<div class="safe">No passive leaks detected.</div>'
    return "\n".join(f'<div class="finding">{hit}</div>' for hit in skimmer_hits)

def _calculate_stats(skimmer_hits: List[str], ai_insights: str) -> Dict[str, Union[int, str]]:
    """Calculate report statistics."""
    total_findings = len(skimmer_hits)
    # Simple heuristic for high-risk items (contains sensitive keywords)
    high_risk_keywords = ['password', 'token', 'key', 'secret', 'credit', 'ssn']
    high_risk = sum(1 for hit in skimmer_hits
                   if any(keyword in hit.lower() for keyword in high_risk_keywords))
    return {
        'total_findings': total_findings,
        'high_risk': high_risk,
        'duration': 'N/A',  # Could be enhanced to track actual duration
    }

def generate_report_text(scope: str, skimmer_hits: Optional[List[str]] = None,
                        ai_insights: str = "", version: str = "1.0") -> str:
    """Generate a markdown security report.

    Args:
        scope: Target scope/domain
        skimmer_hits: List of skimmer findings
        ai_insights: AI analysis summary
        version: Report version

    Returns:
        Formatted markdown report
    """
    if not _validate_inputs(scope, skimmer_hits or [], ai_insights):
        return ""

    skimmer_hits = skimmer_hits or []
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    stats = _calculate_stats(skimmer_hits, ai_insights)

    skimmer_section = _format_skimmer_section(skimmer_hits)

    report = MARKDOWN_TEMPLATE.format(
        timestamp=timestamp,
        scope=scope,
        version=version,
        skimmer_section=skimmer_section,
        ai_section=ai_insights or "No AI analysis performed.",
        **stats
    )

    logger.info(f"Generated markdown report for scope: {scope}")
    return report

